#!/usr/bin/env node
// sync-lua-agents.mjs
// Reads every *.lua file in src/server/lua-agents/agents/ and regenerates
// src/server/lua-agents/scripts.ts so the two never drift apart.
// Usage: node scripts/sync-lua-agents.mjs
//        (also wired into "prebuild" via package.json)

import { readFileSync, writeFileSync, readdirSync } from 'fs';
import { join, basename } from 'path';
import { fileURLToPath } from 'url';
import { dirname } from 'path';

const __dir = dirname(fileURLToPath(import.meta.url));
const root = join(__dir, '..');
const agentsDir = join(root, 'src/server/lua-agents/agents');
const outFile = join(root, 'src/server/lua-agents/scripts.ts');

const files = readdirSync(agentsDir)
  .filter(f => f.endsWith('.lua'))
  .sort();

const exports = [];
const exportNames = [];

for (const file of files) {
  const name = basename(file, '.lua');
  const constName = name.replace(/^_/, '').toUpperCase().replace(/-/g, '_');
  const src = readFileSync(join(agentsDir, file), 'utf8');
  // Escape backticks and ${} in the Lua source so the template literal is safe
  const escaped = src.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  exports.push(`export const ${constName} = \`\n${escaped}\`;`);
  exportNames.push({ constName, name });
}

const banner = `// AUTO-GENERATED by scripts/sync-lua-agents.mjs — do NOT edit manually.
// Run \`node scripts/sync-lua-agents.mjs\` or \`npm run agents:sync\` to regenerate.
// Source files: src/server/lua-agents/agents/*.lua

`;

const content = banner + exports.join('\n\n') + '\n';
writeFileSync(outFile, content, 'utf8');

console.log(`[sync-lua-agents] wrote ${files.length} agents to scripts.ts`);
for (const { constName, name } of exportNames) {
  console.log(`  ${constName} <- ${name}.lua`);
}
